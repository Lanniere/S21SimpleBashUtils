void getRandomFigure(int figure[4][4]) {
    int type = rand() % FIGURE_COUNT;
    int rotation = rand() % 4;
    for (int i = 0; i < 4; i++) {
        for (int j = 0; j < 4; j++) {
            figure[i][j] = FIGURES[type][rotation][i][j];
        }
    }
}

void rotateFigure(int figure[4][4]) {
    int temp[4][4];
    for (int i = 0; i < 4; i++) {
        for (int j = 0; j < 4; j++) {
            temp[j][3-i] = figure[i][j];
        }
    }
    memcpy(figure, temp, sizeof(temp));
}